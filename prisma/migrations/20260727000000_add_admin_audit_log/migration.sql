-- AdminAuditLog — who did what from the operator panel.
--
-- Additive: one new enum, one new table, no column touched on any existing
-- model, no back-relation added to workspaces. Nothing reads it until the
-- Audit tab ships, so a partial rollout degrades to "no rows".
--
-- The load-bearing decision is the ABSENCE of a foreign key on "workspaceId".
-- audit_logs and collaboration_events both cascade from workspaces; an admin
-- log that did the same would delete its own record of DELETE_DEMO along with
-- the workspace it describes. Here it is a plain nullable column that outlives
-- its target — and the trade is that it can name a workspace that no longer
-- exists, which is exactly the point.
--
-- Column types follow the house pattern (see content_generations): TEXT ids
-- generated by Prisma's @default(uuid()), TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP.
-- Deviating (UUID / gen_random_uuid() / TIMESTAMPTZ) would read as drift on the
-- next `prisma migrate diff`.

-- CreateEnum
DO $$ BEGIN
  CREATE TYPE "AdminAuditType" AS ENUM ('CHANGE_ROLE', 'CHANGE_PLAN', 'SEED_DEMO', 'DELETE_DEMO');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

-- CreateTable
CREATE TABLE IF NOT EXISTS "admin_audit_logs" (
    "id" TEXT NOT NULL,
    "actorUid" TEXT NOT NULL,
    "actorEmail" TEXT NOT NULL,
    "type" "AdminAuditType" NOT NULL,
    "targetType" TEXT NOT NULL,
    "targetId" TEXT NOT NULL,
    "workspaceId" TEXT,
    "before" JSONB,
    "after" JSONB,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "admin_audit_logs_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE INDEX IF NOT EXISTS "admin_audit_logs_actorUid_idx" ON "admin_audit_logs"("actorUid");

-- CreateIndex
CREATE INDEX IF NOT EXISTS "admin_audit_logs_workspaceId_idx" ON "admin_audit_logs"("workspaceId");

-- CreateIndex
CREATE INDEX IF NOT EXISTS "admin_audit_logs_createdAt_idx" ON "admin_audit_logs"("createdAt" DESC);
