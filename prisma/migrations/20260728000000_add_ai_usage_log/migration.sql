-- AiUsageLog — one row per provider attempt-sequence made through the AI gateway.
--
-- Additive: one new table, no column touched on any existing model, no
-- back-relation added to workspaces. Nothing reads it until the cost tab ships,
-- so a partial rollout degrades to "no rows".
--
-- No foreign key on "workspaceId", same reasoning as admin_audit_logs: the AI
-- spend a workspace incurred is a fact about money, and deleting the workspace
-- must not delete the record that it cost something. It is a plain nullable
-- column that outlives its target. Nullable because attribution is genuinely
-- best-effort — `workspaceId` is optional on the gateway's public contract, so
-- NULL honestly means "unattributed", never a placeholder workspace.
--
-- Token columns are nullable ON PURPOSE. NULL is "the provider did not report
-- this", which is NOT the same as 0. A failed call measured nothing; storing 0
-- would let the cost tab render it as $0.00, which is a fabricated measurement.
--
-- Column types follow the house pattern (see content_generations,
-- admin_audit_logs): TEXT ids generated by Prisma's @default(uuid()),
-- TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP. Deviating (UUID /
-- gen_random_uuid() / TIMESTAMPTZ / now()) would read as drift on the next
-- `prisma migrate diff`, and gen_random_uuid() additionally needs pgcrypto.

-- CreateTable
CREATE TABLE IF NOT EXISTS "ai_usage_logs" (
    "id" TEXT NOT NULL,
    "workspaceId" TEXT,
    "capability" TEXT NOT NULL,
    "provider" TEXT NOT NULL,
    "model" TEXT,
    "inputTokens" INTEGER,
    "outputTokens" INTEGER,
    "tokens" INTEGER,
    "latencyMs" INTEGER,
    "attempts" INTEGER,
    "success" BOOLEAN NOT NULL DEFAULT true,
    "isFallback" BOOLEAN NOT NULL DEFAULT false,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "ai_usage_logs_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
-- Composite, not workspaceId alone: every read this table exists for is
-- "spend for workspace X over period Y" (mirrors loop_runs).
CREATE INDEX IF NOT EXISTS "ai_usage_logs_workspaceId_createdAt_idx" ON "ai_usage_logs"("workspaceId", "createdAt" DESC);

-- CreateIndex
-- Serves the cross-workspace admin view AND the retention sweep's range delete.
CREATE INDEX IF NOT EXISTS "ai_usage_logs_createdAt_idx" ON "ai_usage_logs"("createdAt" DESC);

-- CreateIndex
CREATE INDEX IF NOT EXISTS "ai_usage_logs_provider_idx" ON "ai_usage_logs"("provider");
